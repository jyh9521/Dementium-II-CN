"""Replay actual shipped table loader -> option getter; file/allocator boundaries only."""
import argparse,hashlib,json,struct
from pathlib import Path
import pefile
from unicorn import Uc,UC_ARCH_X86,UC_MODE_64,UC_HOOK_CODE
from unicorn.x86_const import *
from localize import Zar


def replay(executable,archive):
    return replay_bytes(Path(executable).read_bytes(),Path(archive).read_bytes())

def replay_bytes(exe,rom,image_base=None):
    pe=pefile.PE(data=exe);base=pe.OPTIONAL_HEADER.ImageBase
    data_rva=next(s.VirtualAddress for s in pe.sections if s.Name.rstrip(b'\0')==b'.data')
    profiles={
      0x4cd000:{'build':'26260428','loader':0x12e870,'loader_size':0x399,
        'getter':0x12b5d0,'getter_size':0x328,'hook':0x12b6fa,'indices':0x440a80,
        'open':0x1d1f40,'alloc':0x1b3980,'free':0x1b4000,'memset':0x392d02,
        'loader_hash':'25294ff3102a5f5e6c9aa551ce785cf92cf0323a35c9a890c4920a914b9f958a',
        'getter_hash':'73fc6f1b9cb95931f3e7b5508c705ad4a70235fd7fa3e15a6ac9230d72e683a0'},
      0x4a4000:{'build':'26152271','loader':0x128600,'getter':0x125540,'hook':0x12566a,'indices':0x41cd00,'open':0x1c0f10,'alloc':0x1a4490,'free':0x1a4b10,'memset':0x36cf72,'loader_hash':'776a395358e6297b62e41ff38f7d3fc2aa0181ddfc943caf63d9c5f49942254f','getter_hash':'b29dabb264178d83330e4f184f46d57ab668375d9805c5bab4ff617c908806d7'},
      0x4a1000:{'build':'26123896','loader':0x128260,'getter':0x1251a0,'hook':0x1252ca,'indices':0x41aa90,'open':0x1c08c0,'alloc':0x1a3e40,'free':0x1a44c0,'memset':0x36b592,'loader_hash':'675c972cd94791c321b1785117064a6c200b33d0dab85628b6d6addc3718b579','getter_hash':'27a0fca24e08105af75b2b86e48e9b74860c089466866a214257fc960bbd1337'},
    }
    if data_rva not in profiles:raise ValueError('Unknown native option loader profile')
    profile=profiles[data_rva]
    if hashlib.sha256(pe.get_data(profile['loader'],profile.get('loader_size',0x1f5))).hexdigest()!=profile['loader_hash']:
        raise ValueError('Native option loader source guard mismatch')
    getter_code=bytearray(pe.get_data(profile['getter'],profile.get('getter_size',0x1e0)))
    source=bytes.fromhex('49 63 8c 83')+struct.pack('<I',profile['indices'])
    hook_bytes=pe.get_data(profile['hook'],8)
    if hook_bytes!=source:
        ui=next((s for s in pe.sections if s.Name.rstrip(b'\0')==b'.locui'),None)
        strings=next((s for s in pe.sections if s.Name.rstrip(b'\0')==b'.locmenu'),None)
        if ui is None or strings is None or ui.Characteristics!=0x60000020 or strings.Characteristics!=0x40000040:
            raise ValueError('Native option context sections differ')
        target=profile['hook']+5+struct.unpack('<i',hook_bytes[1:5])[0]
        if hook_bytes[0]!=0xe9 or hook_bytes[5:]!=bytes.fromhex('90 90 90') or target!=ui.VirtualAddress+0xe00:
            raise ValueError('Native option context hook guard mismatch')
        # Validate the entire configured RIP-relative stub, including its literal
        # targets, before normalizing only these eight original getter bytes.
        from option_context import configured_literals,patch_context_literals
        from native_profile import _ACTIVE,restore
        token=_ACTIVE.set(profile['build'])
        try:
            context=configured_literals();pointers={};offset=strings.VirtualAddress
            for key,value in context.get('head_bob',{}).items():
                needle=value.encode('utf8')+b'\0';raw_section=pe.get_data(strings.VirtualAddress,strings.Misc_VirtualSize)
                # Context literals are appended after the glyph text, in key order.
                pos=raw_section.rfind(needle)
                if pos<0:raise ValueError('Missing native context literal')
                pointers[key]=base+strings.VirtualAddress+pos
            if set(pointers)!={'1','2'}:raise ValueError('Missing native context configuration')
            # Reconstruct the expected stub on an otherwise identical unhooked
            # copy with an empty reservation, then compare every generated byte.
            plain=bytearray(exe);pos=pe.get_offset_from_rva(profile['hook']);plain[pos:pos+8]=source
            reservation=pe.get_offset_from_rva(target);plain[reservation:reservation+0x100]=b'\xcc'*0x100
            reconstructed,report=patch_context_literals(bytes(plain),{'head_bob':pointers})
            length=report['code_bytes']
            if reconstructed[reservation:reservation+length]!=exe[reservation:reservation+length]:
                raise ValueError('Native option context code guard mismatch')
        finally:restore(token)
        at=profile['hook']-profile['getter'];getter_code[at:at+8]=source
    if hashlib.sha256(getter_code).hexdigest()!=profile['getter_hash']:
        raise ValueError('Native option getter source guard mismatch')
    raw=Zar(rom).read('EN/OPTIONSNEW.TBL')
    if image_base is not None:
        pe.relocate_image(image_base);base=pe.OPTIONAL_HEADER.ImageBase
    u=Uc(UC_ARCH_X86,UC_MODE_64);u.mem_map(base,(pe.OPTIONAL_HEADER.SizeOfImage+4095)&~4095);u.mem_write(base,pe.get_memory_mapped_image())
    u.mem_map(0x2000000,0x100000)
    context=0x2000000;table=0x2010000;stack=0x2020008;stop=0x2030000;stream=0x2040000;vtable=0x2050000;buffer=0x2060000;name=0x2070000
    u.mem_write(name,b'/en/optionsnew.tbl\0');u.mem_write(stream,struct.pack('<Q',vtable))
    callbacks={base+profile['open']:'open',base+profile['alloc']:'alloc',base+profile['free']:'free',base+profile['memset']:'memset',0x2080000:'size',0x2080010:'read',0x2080020:'close'}
    u.mem_write(vtable+0x40,struct.pack('<Q',0x2080000));u.mem_write(vtable+0x18,struct.pack('<Q',0x2080010));u.mem_write(vtable,struct.pack('<Q',0x2080020))
    calls=[]
    def cstring(address):
        b=bytearray()
        for i in range(16384):
            x=u.mem_read(address+i,1)[0]
            if not x:return bytes(b)
            b.append(x)
        raise ValueError('Unterminated native string')
    def hook(uc,address,size,_):
        kind=callbacks.get(address)
        if not kind:return
        rcx=uc.reg_read(UC_X86_REG_RCX);rdx=uc.reg_read(UC_X86_REG_RDX);r8=uc.reg_read(UC_X86_REG_R8);result=0
        if kind=='open':
            pathptr,length=struct.unpack('<QQ',uc.mem_read(rdx,16));path=cstring(pathptr)
            if path!=b'/en/optionsnew.tbl' or length!=len(path):raise ValueError('Unexpected native VFS file request: '+repr((path,length)))
            result=stream;calls.append({'kind':'open','resource':'EN/OPTIONSNEW.TBL','size':len(raw)})
        elif kind=='size':result=len(raw)
        elif kind=='alloc':
            if rcx<len(raw)+1 or rcx>0x10000:raise ValueError('Unexpected native allocation size')
            result=buffer;calls.append({'kind':'alloc','size':rcx})
        elif kind=='read':
            if rcx!=stream or r8!=len(raw):raise ValueError('Unexpected native stream read')
            uc.mem_write(rdx,raw);result=len(raw)
        elif kind=='memset':uc.mem_write(rcx,bytes([rdx&255])*r8);result=rcx
